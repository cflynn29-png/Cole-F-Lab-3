#addition function
def add(x,y):
    print(x+y)

#subtraction function
def subtract(x,y):
    print(x-y)

#multiplication function
def multiply(x,y):
    print(x*y)


#division function
def divide(x,y):
    print(x/y)

x = int(input("Enter first number: "))
y = int(input("Enter second number: "))

add(x,y)
subtract(x,y)
multiply(x,y)
divide(x,y)